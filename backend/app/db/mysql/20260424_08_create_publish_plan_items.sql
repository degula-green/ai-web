CREATE TABLE IF NOT EXISTS publish_plan_items (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键 ID',
    request_group_id VARCHAR(64) NOT NULL COMMENT '同一次发布请求的分组 ID',
    owner_user_id BIGINT NOT NULL COMMENT '所属用户 ID',
    draft_id VARCHAR(64) NULL COMMENT '关联的草稿 ID',
    task_ref VARCHAR(255) NULL COMMENT '业务侧任务引用 ID',
    platform_type INT NOT NULL COMMENT '平台类型编号',
    platform_code VARCHAR(32) NOT NULL COMMENT '平台编码，如 douyin/xiaohongshu',
    platform_name VARCHAR(64) NOT NULL COMMENT '平台展示名称',
    account_id BIGINT NOT NULL COMMENT '发布账号 ID，对应 platform_accounts.id',
    account_name VARCHAR(255) NOT NULL COMMENT '发布账号名称或昵称',
    title VARCHAR(255) NOT NULL COMMENT '发布标题',
    video_url VARCHAR(2048) NULL COMMENT '发布视频地址',
    cover_url VARCHAR(1024) NULL COMMENT '封面地址',
    topics JSON NOT NULL COMMENT '话题标签列表',
    publish_mode VARCHAR(32) NOT NULL COMMENT '发布模式：headed/headless',
    publish_time_type VARCHAR(32) NOT NULL COMMENT '发布时间类型：now/schedule',
    scheduled_at DATETIME NULL COMMENT '计划发布时间',
    submitted_at DATETIME NULL COMMENT '提交到次级发布程序的时间',
    status VARCHAR(32) NOT NULL COMMENT '发布记录状态：submitted/scheduled/failed',
    status_message VARCHAR(512) NULL COMMENT '状态说明或下游返回摘要',
    downstream_status_code INT NULL COMMENT '下游发布接口状态码',
    downstream_payload JSON NULL COMMENT '发送给下游发布程序的请求体',
    downstream_response JSON NULL COMMENT '下游发布程序返回的响应体',
    extra_data JSON NULL COMMENT '扩展信息',
    failure_reason TEXT NULL COMMENT '失败原因详情',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    KEY idx_publish_plan_items_owner_user_id (owner_user_id),
    KEY idx_publish_plan_items_request_group_id (request_group_id),
    KEY idx_publish_plan_items_draft_id (draft_id),
    KEY idx_publish_plan_items_task_ref (task_ref),
    KEY idx_publish_plan_items_platform_type (platform_type),
    KEY idx_publish_plan_items_platform_code (platform_code),
    KEY idx_publish_plan_items_account_id (account_id),
    KEY idx_publish_plan_items_publish_time_type (publish_time_type),
    KEY idx_publish_plan_items_scheduled_at (scheduled_at),
    KEY idx_publish_plan_items_submitted_at (submitted_at),
    KEY idx_publish_plan_items_status (status),
    KEY idx_publish_plan_items_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='发布计划明细表';
