CREATE TABLE IF NOT EXISTS platform_account_contents (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键 ID',
    owner_user_id BIGINT NOT NULL COMMENT '所属用户 ID',
    account_id BIGINT NOT NULL COMMENT '平台账号 ID，对应 platform_accounts.id',
    platform_code VARCHAR(32) NOT NULL COMMENT '平台编码',
    sec_user_id VARCHAR(255) NULL COMMENT '创作者 sec_user_id',
    content_id VARCHAR(128) NOT NULL COMMENT '统一内容 ID',
    content_type VARCHAR(32) NOT NULL COMMENT '内容类型：video/image/unpublished',
    content_status VARCHAR(32) NOT NULL COMMENT '内容状态：published/pending',
    dy_aweme_id VARCHAR(64) NULL COMMENT '抖音 aweme_id',
    xhs_note_id VARCHAR(64) NULL COMMENT '小红书 note_id',
    bili_video_id VARCHAR(64) NULL COMMENT 'Bilibili video id',
    ks_video_id VARCHAR(64) NULL COMMENT '快手 video id',
    title VARCHAR(255) NULL COMMENT '标题',
    cover_url VARCHAR(1024) NULL COMMENT '封面地址',
    content_url VARCHAR(2048) NULL COMMENT '内容地址',
    author_name VARCHAR(255) NULL COMMENT '作者昵称',
    aweme_type VARCHAR(16) NULL COMMENT '平台原始类型',
    liked_count INT NOT NULL DEFAULT 0 COMMENT '点赞数',
    comment_count INT NOT NULL DEFAULT 0 COMMENT '评论数',
    share_count INT NOT NULL DEFAULT 0 COMMENT '分享数',
    published_at DATETIME NULL COMMENT '平台发布时间',
    last_synced_at DATETIME NULL COMMENT '最后同步时间',
    extra_data JSON NULL COMMENT '扩展数据',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    UNIQUE KEY uk_pac_owner_account_platform_content (owner_user_id, account_id, platform_code, content_id),
    KEY idx_pac_owner_user_id (owner_user_id),
    KEY idx_pac_account_id (account_id),
    KEY idx_pac_platform_code (platform_code),
    KEY idx_pac_sec_user_id (sec_user_id),
    KEY idx_pac_content_status (content_status),
    KEY idx_pac_content_type (content_type),
    KEY idx_pac_published_at (published_at),
    KEY idx_pac_dy_aweme_id (dy_aweme_id),
    KEY idx_pac_xhs_note_id (xhs_note_id),
    KEY idx_pac_bili_video_id (bili_video_id),
    KEY idx_pac_ks_video_id (ks_video_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='平台账号自有内容索引表';
